
-- Goals Table (Personal)
CREATE TABLE public.goals (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  name text not null,
  target_amount numeric not null,
  current_amount numeric default 0 not null,
  color text default 'bg-blue-500',
  icon text default 'faStar',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);
ALTER TABLE public.goals ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users manage own goals" ON public.goals USING (user_id = auth.uid());

-- Calendar Table (Personal)
CREATE TABLE public.calendar_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  title text not null,
  event_date date not null,
  color text default 'bg-pink-500',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);
ALTER TABLE public.calendar_events ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users manage own events" ON public.calendar_events USING (user_id = auth.uid());

